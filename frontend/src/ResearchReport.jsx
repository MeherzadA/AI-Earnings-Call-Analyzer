import { useEffect, useRef, useState } from "react";
import { apiRequest } from "./api.js";

const SUBJECTS = { performance: "Performance", guidance: "Management guidance", risks: "Risks", opportunities: "Opportunities" };

function Evidence({ citations, onSource }) {
  return <details className="finding-evidence">
    <summary>View evidence <span>{citations.length} source {citations.length === 1 ? "passage" : "passages"}</span></summary>
    {citations.map((citation, i) => <div className="evidence-excerpt" key={i}>
      <div className="evidence-caption"><span>Source excerpt matched</span><span>{citation.passage_id}</span></div>
      <blockquote>{citation.quote}</blockquote>
      <button type="button" onClick={() => onSource(citation)}>Read in transcript <span aria-hidden="true">↗</span></button>
    </div>)}
  </details>;
}

function FindingCard({ finding, index, onSource }) {
  return <article className={`finding-card category-${finding.category}`}>
    <div className="finding-number" aria-hidden="true">{String(index + 1).padStart(2, "0")}</div>
    <div className="finding-body">
      <p className="finding-subject">{SUBJECTS[finding.category]}</p>
      <h3>{finding.headline}</h3>
      <div className="finding-columns">
        <div><h4>AI observation</h4><p>{finding.observation}</p></div>
        {finding.interpretation && <div className="finding-interpretation"><h4>AI interpretation</h4><p>{finding.interpretation}</p></div>}
      </div>
      <Evidence citations={finding.citations} onSource={onSource} />
    </div>
  </article>;
}

function SourceViewer({ reportId, citation, expectedHash, onClose }) {
  const dialog = useRef(null);
  const [data, setData] = useState(null);
  const [error, setError] = useState("");
  const [retry, setRetry] = useState(0);
  useEffect(() => {
    dialog.current.showModal();
  }, []);
  useEffect(() => {
    let cancelled = false;
    setError(""); setData(null);
    apiRequest(`/reports/${reportId}/transcript`).then((source) => {
      if (cancelled) return;
      if (expectedHash && source.source_hash !== expectedHash) {
        setError("This transcript no longer matches the report's source. Run a new analysis before using these citations.");
      } else setData(source);
    }).catch((err) => { if (!cancelled) setError(err.message); });
    return () => { cancelled = true; };
  }, [reportId, expectedHash, retry]);
  useEffect(() => {
    if (data && citation) dialog.current.querySelector(`[data-passage="${citation.passage_id}"]`)?.scrollIntoView({ block: "center" });
  }, [data, citation]);
  return <dialog ref={dialog} className="source-dialog" aria-labelledby="source-title" onClose={onClose} onClick={(event) => { if (event.target === event.currentTarget) dialog.current.close(); }}>
    <div className="source-dialog-header"><div><p className="eyebrow">ORIGINAL SOURCE</p><h2 id="source-title">The earnings call transcript</h2></div><button type="button" autoFocus onClick={() => dialog.current.close()} aria-label="Close transcript">×</button></div>
    <p className="source-context-note">The highlighted excerpt matches the stored transcript. Read the surrounding context to assess the AI's interpretation. Passage numbers are generated by this app.</p>
    <div className="source-dialog-content">
      {!data && !error && <p role="status">Loading the saved transcript…</p>}
      {error && <div role="alert"><p>{error}</p><button type="button" className="text-btn" onClick={() => setRetry((n) => n + 1)}>Try again</button></div>}
      {data?.passages.map((passage) => {
        const selected = citation?.passage_id === passage.id;
        const start = selected ? citation.start - passage.start : 0;
        const end = selected ? citation.end - passage.start : 0;
        const characters = selected ? Array.from(passage.text) : null;
        return <section key={passage.id} data-passage={passage.id} className={selected ? "source-passage source-selected" : "source-passage"}>
          <h3>{passage.id}</h3><p>{selected ? <>{characters.slice(0, start).join("")}<mark>{characters.slice(start, end).join("")}</mark>{characters.slice(end).join("")}</> : passage.text}</p>
        </section>;
      })}
    </div>
  </dialog>;
}

export default function ResearchReport({ result, onUpgrade }) {
  const [source, setSource] = useState(undefined);
  const research = result.research;
  const openSource = (citation = null) => setSource(citation);
  return <>
    {research ? <>
      <div className="report-intro"><span className="tone-tag">Management tone: {research.management_tone} <span>· AI assessment</span></span><button type="button" className="text-btn" onClick={() => openSource()}>Read full transcript ↗</button></div>
      <details className="checks-explainer"><summary>What has been checked?</summary>
        <p>Every displayed citation was matched to the saved transcript. Numeric values were compared with the cited excerpts. These checks do not establish that a claim or AI interpretation is supported, or that management’s statements are true.</p>
        <p>Human review: <strong>not performed</strong>. {research.checks.discarded.length > 0 && `${research.checks.discarded.length} proposed items were omitted because source checks failed.`}</p>
        {research.curation && <p>Selected statements in this example received a development-time AI review. {research.curation.changes.length} unsupported interpretations were removed. <a href="/review.html">Inspect the assessments and original drafts ↗</a></p>}
        <p className="report-provenance">{research.model} · {research.prompt_version} · {new Date(research.generated_at).toLocaleDateString()}</p>
        <a href="https://github.com/MeherzadA/AI-Earnings-Call-Analyzer/blob/main/docs/evaluation.md" target="_blank" rel="noreferrer">Evaluation method and limitations ↗</a>
      </details>
      {research.financial_highlights.length > 0 && <section className="financial-highlights" aria-label="Financial highlights">{research.financial_highlights.map((metric) => <article className="financial-highlight" key={metric.id}>
        <h3>{metric.label}</h3><p className="financial-value">{metric.value}</p><Evidence citations={metric.citations} onSource={openSource} />
      </article>)}</section>}
      <section className="research-findings" aria-labelledby="findings-title">
        <div className="section-heading"><div><p className="eyebrow">THE QUARTER, IN FOCUS</p><h2 id="findings-title">What deserves your attention</h2></div><span>{research.findings.length} prioritized findings</span></div>
        <p className="section-description">AI-written observations and interpretations, with their source evidence. Guidance describes management’s expectations.</p>
        {research.findings.slice(0, 3).map((finding, i) => <FindingCard key={finding.id} finding={finding} index={i} onSource={openSource} />)}
        {research.findings.length > 3 && <details className="more-findings"><summary>Explore {research.findings.length - 3} more {research.findings.length === 4 ? "finding" : "findings"} <span aria-hidden="true">↓</span></summary>
          {Object.entries(SUBJECTS).map(([category, label]) => {
            const remaining = research.findings.slice(3).filter((f) => f.category === category);
            return remaining.length > 0 && <section className="finding-group" key={category}><h3>{label}</h3>{remaining.map((finding) => <FindingCard key={finding.id} finding={finding} index={research.findings.indexOf(finding)} onSource={openSource} />)}</section>;
          })}
        </details>}
      </section>
    </> : <section className="legacy-report">
      <div className="legacy-notice"><div><h2>This is an earlier report</h2><p>Source checks are unavailable for this version. Generate a new brief from the saved transcript; the original report is retained.</p></div><button className="outline-btn" type="button" onClick={onUpgrade}>Build source-based report ↗</button></div>
      <div className="card legacy-summary"><p className="card-label">Earlier AI summary</p><p>{result.analysis.summary}</p><button type="button" className="text-btn" onClick={() => openSource()}>Read the saved transcript ↗</button></div>
      {[["Key claims", result.analysis.key_claims], ["Risks", result.analysis.red_flags], ["Opportunities", result.analysis.opportunities]].map(([title, items]) => <details className="legacy-list" key={title}><summary>{title} <span>{items?.length || 0}</span></summary><ul>{items?.map((item, i) => <li key={i}>{item}</li>)}</ul>{!items?.length && <p>None listed in the earlier report.</p>}</details>)}
    </section>}
    {source !== undefined && <SourceViewer reportId={result.report_id} citation={source} expectedHash={research?.source_hash} onClose={() => setSource(undefined)} />}
  </>;
}
